"""Regenerate the slag half of data/unified/FeC-FeOMgOSiO2.utdb from its registry part,
data/feo-mgo-sio2/FeO-MgO-SiO2-combined.dat.

The steel half (Fe-C after FeC.tdb) is kept verbatim. The slag liquid (renamed SLAG_LIQUID),
olivine, orthopyroxene and magnesiowustite come from the engine's own uTDB writer; cristobalite
keeps its one-species form (SIO2) with the writer's Gibbs function. Run after any
rebuild of the combined FeO-MgO-SiO2 file, then scripts/sync_databases.py to ship it;
tests/test_utdb_steel_roundtrip.py checks both halves against their sources.

Run:  python scripts/build_steel_slag_utdb.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python"))
import mqmqa

UTDB = ROOT / "data" / "unified" / "FeC-FeOMgOSiO2.utdb"
DAT = ROOT / "data" / "feo-mgo-sio2" / "FeO-MgO-SiO2-combined.dat"
MARK = "$ ---------- FeO-MgO-SiO2 slag"
OXIDES = {"CRISTOBALITE": "SIO2"}


def _blocks(text):
    """Split writer output into {phase name: lines} for every PHASE statement."""
    out, cur = {}, None
    for line in text.splitlines():
        m = re.match(r" PHASE (\S+)", line)
        if m:
            cur = m.group(1).split(":")[0]
            out[cur] = []
        if cur:
            out[cur].append(line)
    return out


def build():
    steel = UTDB.read_text(encoding="utf-8").split(MARK)[0]
    blocks = _blocks(mqmqa.Database.read(str(DAT)).write_utdb())
    lines = [MARK + " (uTDB :Q extension + plain TDB) ----------",
             "$ Generated by scripts/build_steel_slag_utdb.py from data/feo-mgo-sio2/FeO-MgO-SiO2-combined.dat;",
             "$ per-pair Gibbs on the (1, T, T lnT, T^2, T^3, 1/T) basis, per mole of oxide formula.",
             ""]
    for name in ("FEO-MGO-SIO2-LIQUID", "OLIVINE", "ORTHOPYROXENE", "MAGNESIOWUSTITE"):
        body = "\n".join(blocks[name]).replace("FEO-MGO-SIO2-LIQUID", "SLAG_LIQUID")
        lines += body.rstrip().splitlines() + [""]
    for name, sp in OXIDES.items():
        body = blocks[name]
        start = next(i for i, l in enumerate(body) if l.startswith(" PARAMETER G("))
        par = body[start].split(";0)", 1)
        lines += [f" PHASE {name} %  1  1.0 !", f" CONSTITUENT {name} : {sp} : !",
                  f" PARAMETER G({name},{sp};0)" + par[1]]
        while body and not body[-1].strip():
            body = body[:-1]
        lines += body[start + 1:] + [""]
    UTDB.write_text(steel + "\n".join(lines).rstrip() + "\n", encoding="utf-8", newline="\n")
    return UTDB


if __name__ == "__main__":
    print("wrote", build())
