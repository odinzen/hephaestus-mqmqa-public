"""Build Thermochimica input scripts for every condition, run them in WSL, and collect the results.

Usage:
    python run_thermochimica.py build    # adds the extended grid to conditions.json, writes ti/*.ti and run_all.sh
    python run_thermochimica.py collect  # reads the raw JSON/logs from the sealed folder into thermochimica_results.json

Raw output goes straight to the sealed folder; nothing numeric is written here.
"""
import json
import os
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
CONDITIONS = HERE.parent / "conditions.json"
TI_DIR = HERE / "ti"
# the sealed folder lives outside the repository
SEALED = Path(os.environ.get("SEALED_DIR", HERE.parents[2] / "sealed"))
RAW = SEALED / "thermochimica_raw"
TC_WSL = os.environ.get("THERMOCHIMICA_DIR", "THERMOCHIMICA_DIR")  # Thermochimica checkout, as a WSL path
GRID_LOWER_K = 298.15  # ChemSage/SGTE Gibbs functions start at 298.15 K; the .dat files state no other limit

SYMBOLS = (
    "H He Li Be B C N O F Ne Na Mg Al Si P S Cl Ar K Ca Sc Ti V Cr Mn Fe Co Ni Cu Zn Ga Ge As Se Br Kr "
    "Rb Sr Y Zr Nb Mo Tc Ru Rh Pd Ag Cd In Sn Sb Te I Xe Cs Ba La Ce Pr Nd Pm Sm Eu Gd Tb Dy Ho Er Tm "
    "Yb Lu Hf Ta W Re Os Ir Pt Au Hg Tl Pb Bi Po At Rn Fr Ra Ac Th Pa U Np Pu Am Cm Bk Cf Es Fm Md No"
).split()
Z = {s: i + 1 for i, s in enumerate(SYMBOLS)}


def wsl_path(p):
    p = str(Path(p).resolve()).replace("\\", "/")
    return "/mnt/" + p[0].lower() + p[2:]


def to_kelvin(t, unit):
    return {"K": t, "C": t + 273.15}[unit]


def ti_text(c, *, heat_capacity=False, out_json=None, omit=(), overrides=None):
    o = overrides or {}
    lines = []
    if "temperature" not in omit:
        lines.append(f"temperature       = {o.get('temperature', c['temperature'])!r}")
    if "pressure" not in omit:
        lines.append(f"pressure          = {o.get('pressure', c['pressure'])}")
    if "mass" not in omit:
        for el, amt in o.get("element_amounts", c["element_amounts"]).items():
            lines.append(f"mass({Z[el]})".ljust(18) + f"= {amt!r}")
    if "units" not in omit:
        lines += [f"temperature unit  = {o.get('temperature_unit', c['temperature_unit'])}",
                  f"pressure unit     = {c['pressure_unit']}",
                  f"mass unit         = {o.get('mass_unit', c['mass_unit'])}"]
    lines += [f"data file         = {TC_WSL}/data/{c['database']}",
              "print mode        = 0",
              f"heat capacity     = {'.TRUE.' if heat_capacity else '.FALSE.'}",
              "write json        = .TRUE.",
              f"output            = {out_json}"]
    return "! Generated by run_thermochimica.py from conditions.json (conditions only)\n" + "\n".join(lines) + "\n"


# How each input-validation test is expressed as an input script. The test programs set every element
# (dElementMass = x for the whole array); a script can only name elements, so the database's own two
# elements (C and O in CO.dat) carry that amount.
VALIDATION = {
    "TestThermo03": dict(omit=("units",)),
    "TestThermo04": dict(omit=("temperature",)),
    "TestThermo05": dict(omit=("pressure",)),
    "TestThermo06": dict(omit=("mass",)),
    "TestThermo07": dict(),
    "TestThermo08": dict(),
    "TestThermo09": dict(),
    "TestThermo10": dict(overrides={"pressure": "NaN"}),
    "TestThermo11": dict(overrides={"temperature": 1e74}),
    "TestThermo12": dict(),
    "TestThermo13": dict(),
}


def build():
    data = json.loads(CONDITIONS.read_text())
    TI_DIR.mkdir(exist_ok=True)
    RAW.mkdir(parents=True, exist_ok=True)
    runs, grid, not_run = [], [], []
    for c in data["conditions"]:
        cid, cat = c["id"], c["category"]
        if cat == "parse_only":
            not_run.append({"id": cid, "reason": "parse-only test, no equilibrium condition"})
            continue
        if cat == "equilibrium_modified_data":
            not_run.append({"id": cid, "reason": "test changes SUBQ zeta values in memory after parsing; an input "
                            "script cannot reproduce that (the compiled test program passes)"})
            continue
        if cat == "input_validation":
            spec = VALIDATION[cid]
            cc = dict(c)
            if c["all_elements_amount"] is not None and not c["element_amounts"]:
                cc["element_amounts"] = {el: c["all_elements_amount"] for el in data["databases"][c["database"]]["elements_in_file_order"]}
            runs.append((cid, ti_text(cc, out_json=f"{wsl_path(RAW)}/{cid}.json", **spec), "test"))
            continue
        runs.append((cid, ti_text(c, out_json=f"{wsl_path(RAW)}/{cid}.json"), "test"))
        if "heat_capacity" in c["quantities_checked"]:
            runs.append((cid + "__cp", ti_text(c, heat_capacity=True, out_json=f"{wsl_path(RAW)}/{cid}__cp.json"), "test_cp"))
        t_k = to_kelvin(c["temperature"], c["temperature_unit"])
        for i, dt in enumerate((-200, -100, 0, 100, 200), start=1):
            t = round(t_k + dt, 6)
            gid = f"{cid}__grid{i}"
            entry = {"id": gid, "grid": "extended", "based_on": cid, "database": c["database"],
                     "temperature": t, "temperature_unit": "K",
                     "pressure": c["pressure"], "pressure_unit": c["pressure_unit"],
                     "element_amounts": c["element_amounts"], "mass_unit": c["mass_unit"],
                     "same_as_test_condition": dt == 0}
            if t < GRID_LOWER_K:
                entry["skipped"] = f"below {GRID_LOWER_K} K, the lower limit of the data"
                grid.append(entry)
                continue
            grid.append(entry)
            runs.append((gid, ti_text(c, out_json=f"{wsl_path(RAW)}/{gid}.json",
                                      overrides={"temperature": t, "temperature_unit": "K"}), "grid"))
    data["extended_grid_rule"] = ("for each equilibrium test composition: T-200, T-100, T, T+100, T+200 K at the "
                                  f"test pressure; points below {GRID_LOWER_K} K are listed but not run. The .dat "
                                  "files state no upper limit; Gibbs functions are used as Thermochimica reads them.")
    data["extended_grid"] = grid
    data["not_run_with_thermochimica"] = not_run
    CONDITIONS.write_text(json.dumps(data, indent=1))
    for rid, text, _ in runs:
        (TI_DIR / f"{rid}.ti").write_text(text, newline="\n")
    (HERE / "run_list.json").write_text(json.dumps([{"id": r, "kind": k} for r, _, k in runs], indent=1))
    script = f"""#!/usr/bin/env bash
# Runs every input script in ti/ with Thermochimica's InputScriptMode; output goes to the sealed folder.
source ~/miniforge3/etc/profile.d/conda.sh && conda activate thermochimica
cd {TC_WSL}
RAW={wsl_path(RAW)}
for f in {wsl_path(TI_DIR)}/*.ti; do
  id=$(basename "$f" .ti)
  timeout 120 ./bin/InputScriptMode "$f" > "$RAW/$id.log" 2>&1
  echo "exit=$?" >> "$RAW/$id.log"
done
"""
    (HERE / "run_all.sh").write_text(script, newline="\n")
    print(f"runs {len(runs)} (grid {sum(1 for r in runs if r[2] == 'grid')}), "
          f"grid points listed {len(grid)}, grid points skipped {sum(1 for g in grid if 'skipped' in g)}, not run {len(not_run)}")


def stable(d):
    phases = {}
    for name, ph in d.get("solution phases", {}).items():
        if ph.get("moles", 0) > 0:
            phases[name] = {"type": "solution", "model": ph.get("phase model"), "moles": ph["moles"],
                            "species_mole_fractions": {s: v.get("mole fraction") for s, v in ph.get("species", {}).items()}}
    for name, ph in d.get("pure condensed phases", {}).items():
        if ph.get("moles", 0) > 0:
            phases[name] = {"type": "pure_condensed", "moles": ph["moles"]}
    return phases


def _compiled_status(test):
    log = RAW / f"{test}_compiled_test.log"
    if not log.exists():
        return "not run"
    text = log.read_text(errors="replace")
    return "PASS" if "PASS" in text and "exit=0" in text else "FAIL"


def collect():
    runs = json.loads((HERE / "run_list.json").read_text())
    results, n_fail = {}, 0
    for r in runs:
        rid = r["id"]
        log = (RAW / f"{rid}.log").read_text(errors="replace") if (RAW / f"{rid}.log").exists() else ""
        debug = [ln.strip() for ln in log.splitlines() if ln.strip() and not ln.startswith("exit=")]
        exit_line = re.search(r"exit=(\d+)", log)
        jpath = RAW / f"{rid}.json"
        d = None
        if jpath.exists():
            try:
                raw = json.loads(jpath.read_text())
                d = raw.get("1") or None
            except json.JSONDecodeError as e:
                debug.append(f"JSON unreadable: {e}")
        rec = {"kind": r["kind"], "exit_code": int(exit_line.group(1)) if exit_line else None,
               "messages": debug}
        ok = bool(d) and any("Successful exit" in m for m in debug)
        rec["status"] = "ok" if ok else "failed"
        if not ok:
            n_fail += 1
        if d:
            rec["stable_phases"] = stable(d)
            rec["integral_gibbs_energy_J"] = d.get("integral Gibbs energy")
            rec["element_chemical_potentials_J_per_mol"] = {el: v.get("element potential") for el, v in d.get("elements", {}).items()}
            rec["heat_capacity_J_per_K"] = d.get("heat capacity") if r["kind"] == "test_cp" else None
            rec["temperature_K"] = d.get("temperature")
            rec["pressure"] = d.get("pressure")
            rec["system_species_order"] = (
                [f"{ph}:{sp}" for ph, v in d.get("solution phases", {}).items() for sp in v.get("species", {})]
                + list(d.get("pure condensed phases", {})))
        results[rid] = rec
    out = {
        "producer": "Thermochimica (ORNL-CEES/thermochimica commit 1c076b20f958be65bac750f00af2e59ef4f28d9e), "
                    "InputScriptMode, gfortran build in WSL",
        "units": {"integral_gibbs_energy_J": "J", "element_chemical_potentials_J_per_mol": "J/mol",
                  "moles": "mol", "heat_capacity_J_per_K": "J/K"},
        "stable_phase_rule": "a phase is stable when Thermochimica reports moles > 0",
        "phase_name_note": "NAME#n is a further instance of solution phase NAME across a miscibility gap",
        "element_order_note": "element keys follow the database's element order with absent elements removed, which "
                              "is the order Thermochimica's dElementPotential(i) index uses in the test programs",
        "system_species_order_note": "phase:species in the order the JSON lists them, then pure condensed phases; "
                                     "whether this equals Thermochimica's internal species index is not verified",
        "not_run_by_input_script": {
            "TestThermo14": "parse-only test, no equilibrium condition",
            "TestSUBQNonuniformZeta": "changes SUBQ zeta values in memory; not expressible as an input script. "
                                      "The compiled test program was run instead; its log is "
                                      "thermochimica_raw/TestSUBQNonuniformZeta_compiled_test.log",
        },
        "compiled_test_status": {"TestSUBQNonuniformZeta": _compiled_status("TestSUBQNonuniformZeta")},
        "raw_output_folder": str(RAW),
        "results": results,
    }
    (SEALED / "thermochimica_results.json").write_text(json.dumps(out, indent=1))
    print(f"collected {len(results)}; failed {n_fail}")


if __name__ == "__main__":
    {"build": build, "collect": collect}[sys.argv[1]]()
